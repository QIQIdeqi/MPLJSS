"""Prepare and extract native imagegen rows with the installed sprite-gen engine."""
from pathlib import Path
import json, subprocess
root=Path(__file__).resolve().parents[1]
workspace=root.parents[1]
out=root/'ArtSource/RoseMageAnimation_20261031'
tool=workspace/'01_Skill/installed/sprite-gen/.venv/Scripts/sprite-gen.exe'
for direction in ('Front','Back','Side'):
    folder=out/direction
    base=folder/'run/base-source.png'
    assert base.is_file(), f'Missing archived base image: {base}'
    for action in ('walk','hurt','death'):
        raw=folder/'run/raw'/f'{action}.png'
        assert raw.is_file(), f'Missing archived action strip: {raw}'
    request={'states':{
        'walk':{'frames':6,'fps':8,'loop':True,'action':'Alternating articulated two-step walk in place in the approved direction.'},
        'hurt':{'frames':4,'fps':10,'loop':False,'action':'Brace, recoil with bent knees, recover, neutral.'},
        'death':{'frames':6,'fps':8,'loop':False,'action':'Knees buckle, kneel, collapse, prone and remain down. Never scale low poses to standing height.'}},
        'fit':{'resample':'nearest','align_y':'bottom','align_x':'bbox-center','pixel_unfake':False},
        'style':'Exact approved white-haired rose mage identity and pixel art. Native imagegen row per action; no rotated idle substitutes.'}
    request_path=folder/'request.json'
    request_path.write_text(json.dumps(request,indent=2),encoding='utf-8')
    if not (folder/'run/sprite-request.json').is_file():
        subprocess.run([str(tool),'prepare','--out-dir',str(folder/'run'),'--character-id','rose-mage-'+direction.lower(),'--base-image',str(base),'--request',str(request_path),'--cell-size','512','--safe-margin','24','--chroma-key','#00FFFF','--no-fit-pixel-unfake'],check=True)
    (folder/'run/qa-notes.md').write_text('Generated by built-in image_gen, one true pose row per state. Existing directional anchor used as the exact identity reference. No CLI/API generation or fixed-grid cutting. Death ends prone; loop/stride and in-engine acceptance remain separate checks.\n',encoding='utf-8')
    subprocess.run([str(tool),'extract','--run-dir',str(folder/'run'),'--segmentation','components'],check=True)
    subprocess.run([str(tool),'compose-atlas','--run-dir',str(folder/'run')],check=True)
    subprocess.run([str(tool),'preview','--run-dir',str(folder/'run')],check=True)
    subprocess.run([str(tool),'inspect','--run-dir',str(folder/'run')],check=True)
    subprocess.run([str(tool),'export-pngs','--run-dir',str(folder/'run')],check=True)
